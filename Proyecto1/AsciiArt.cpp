#ifdef _WIN32
    #include <windows.h>
    void gotoxy(int x, int y) {
        HANDLE hcon = GetStdHandle(STD_OUTPUT_HANDLE);
        COORD dwPos;
        dwPos.X = x;
        dwPos.Y = y;
        SetConsoleCursorPosition(hcon, dwPos);
    }
#else
    #include <iostream>
    void gotoxy(int x, int y) {
        cout << "\033[" << y + 1 << ";" << x + 1 << "H";
    }
#endif


